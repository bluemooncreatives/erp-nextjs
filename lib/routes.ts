export type RouteName = keyof typeof ROUTES;

/**
 * Build a URL for a named route.
 *
 *   route('sale.index')                       -> '/sale/sale'
 *   route('sale.edit', { id: 7 })             -> '/sale/sale/7/edit'
 *   route('sale.index', {}, { page: 2 })      -> '/sale/sale?page=2'
 *
 * Unknown parameters become query-string entries, matching Laravel's helper.
 */
export function route(
  name: RouteName,
  params: Record<string, string | number | null | undefined> = {},
  query: Record<string, string | number | boolean | null | undefined> = {},
): string {
  let path: string = ROUTES[name];
  const used = new Set<string>();

  path = path.replace(/\{(\w+)\??\}/g, (_match, key: string) => {
    used.add(key);
    const value = params[key];
    return value == null ? '' : encodeURIComponent(String(value));
  });

  // Drop the trailing segment left behind by an omitted optional parameter.
  path = path.replace(/\/+$/, '') || '/';

  const search = new URLSearchParams();
  for (const [k, v] of Object.entries(params)) {
    if (!used.has(k) && v != null) search.set(k, String(v));
  }
  for (const [k, v] of Object.entries(query)) {
    if (v != null && v !== false && v !== '') search.set(k, String(v));
  }

  const qs = search.toString();
  return qs ? `${path}?${qs}` : path;
}

/** True when `pathname` is the page for `name` - drives sidebar highlighting. */
export function isRouteActive(pathname: string, name: RouteName): boolean {
  const pattern = ROUTES[name].replace(/\{\w+\??\}/g, '[^/]+');
  return new RegExp(`^${pattern}/?$`).test(pathname);
}

/** True when `pathname` sits underneath the route - for parent menu groups. */
export function isRouteSectionActive(pathname: string, prefix: string): boolean {
  return pathname === prefix || pathname.startsWith(`${prefix}/`);
}
